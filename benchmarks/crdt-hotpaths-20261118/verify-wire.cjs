const assert = require('node:assert/strict')
const [baselinePath, candidatePath] = process.argv.slice(2)
const baseline = require(baselinePath)
const candidate = require(candidatePath)

function create(wasm) {
  const doc = new wasm.LoroDoc()
  doc.setPeerId('123')
  doc.configTextStyle({ bold: { expand: 'after' } })
  doc.setChangeMergeInterval(1000)
  const text = doc.getText('text')
  const list = doc.getList('list')
  const movable = doc.getMovableList('movable')
  const map = doc.getMap('map')
  const counter = doc.getCounter('counter')
  const tree = doc.getTree('tree')
  tree.enableFractionalIndex(0)
  const updates = []
  const unsubscribe = doc.subscribeLocalUpdates(bytes => updates.push(Buffer.from(bytes)))
  const commit = (timestamp, message) => doc.commit({ timestamp, message })
  text.insert(0, 'a中😀')
  commit(100, 'typed')
  text.insert(4, 'b')
  commit(101, 'typed')
  text.mark({ start: 0, end: 4 }, 'bold', true)
  list.insert(0, 'x')
  movable.insert(0, 'b')
  movable.insert(1, 'c')
  const a = tree.createNode()
  const b = tree.createNode()
  commit(105, 'containers')
  text.unmark({ start: 1, end: 2 }, 'bold')
  list.delete(0, 1)
  movable.set(0, 'q')
  movable.move(0, 1)
  movable.delete(0, 1)
  tree.move(b.id, a.id)
  map.set('nested', { x: ['a', 1], y: false })
  counter.increment(3)
  commit(107, 'modified containers')
  unsubscribe()
  return { doc, updates }
}

const old = create(baseline)
const next = create(candidate)
assert.deepEqual(next.updates, old.updates)
assert.equal(next.updates.length, 4)
assert.deepEqual(next.doc.toJSON(), old.doc.toJSON())
for (const [target, source] of [[baseline, next], [candidate, old]]) {
  const receiver = new target.LoroDoc()
  for (const update of source.updates) {
    assert.equal(receiver.import(update).pending, null)
  }
  assert.deepEqual(receiver.toJSON(), source.doc.toJSON())
  assert.deepEqual(receiver.frontiers(), source.doc.frontiers())
  assert.deepEqual(receiver.getText('text').toDelta(), source.doc.getText('text').toDelta())
  const roundtrip = new target.LoroDoc()
  roundtrip.import(source.doc.export({ mode: 'snapshot' }))
  assert.deepEqual(roundtrip.toJSON(), source.doc.toJSON())
  assert.deepEqual(roundtrip.frontiers(), source.doc.frontiers())
}
console.log('Four local update blobs are byte-identical. Both builds read each other’s updates and snapshots.')
